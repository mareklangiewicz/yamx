// Assemble the static page: site/ sources, the exact standalone JS libraries
// and generated data (commit, revisions, copy facts, examples). No bundler.
// Usage: node scripts/site.mjs [OUTPUT=_site]
import { execFileSync } from 'node:child_process';
import { copyFileSync, cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { root } from './distribute.mjs';
import { example, facts, rawBase, repository } from './copy-guide.mjs';
import { profileFolders } from './usage-paths.mjs';

/** Page examples from the manifest, with their text. */
export function pageExamples(directory = root) {
  const folder = join(directory, 'examples/page');
  return JSON.parse(readFileSync(join(folder, 'manifest.json'), 'utf8'))
    .map(entry => ({ ...entry, text: readFileSync(join(folder, entry.file), 'utf8') }));
}

/** The commit being built and whether the working tree differs from it. */
export function revision(directory = root) {
  const git = (...args) => execFileSync('git', args, { cwd: directory, encoding: 'utf8' }).trim();
  return { commit: git('rev-parse', 'HEAD'), dirty: git('status', '--porcelain', '--untracked-files=no').length > 0 };
}

export function siteData(directory = root, { commit, dirty } = revision(directory)) {
  if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error(`not a full commit id: ${commit}`);
  return {
    repository, commit, dirty,
    profiles: facts(directory),
    // The documented B shell example, pinned to the built commit like every page link.
    copyExample: example('shell', 'B').replace(`${rawBase}/`, `${rawBase.replace('/main/', `/${commit}/`)}/`),
    examples: pageExamples(directory).map(({ id, profile, label, text }) => ({ id, profile, label, text })),
  };
}

export function build(output, directory = root, data = siteData(directory)) {
  rmSync(output, { recursive: true, force: true });
  cpSync(join(directory, 'site'), output, { recursive: true });
  for (const folder of Object.values(profileFolders)) {
    mkdirSync(join(output, 'lib', folder), { recursive: true });
    copyFileSync(join(directory, 'dist', folder, 'yamx.mjs'), join(output, 'lib', folder, 'yamx.mjs'));
  }
  writeFileSync(join(output, 'generated.mjs'),
    `// Generated by scripts/site.mjs; do not edit.\nexport default ${JSON.stringify(data, null, 2)};\n`);
  return data;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const output = resolve(process.argv[2] ?? join(root, '_site'));
  const data = build(output);
  console.log(`Built ${output} from ${data.commit}${data.dirty ? ' (with uncommitted changes)' : ''}`);
}
